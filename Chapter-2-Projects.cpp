#include <iostream>

using namespace std;

int main()
{
	const float RISE_RATE = 1.5;

	cout << "After 5 years, the ocean will rise by " << 5 * RISE_RATE << " mm \n";
	cout << "After 7 years, the ocean will rise by " << 7 * RISE_RATE << " mm \n";
	cout << "After 10 years, the ocean will rise by " << 10 * RISE_RATE << " mm";
}